"""Render measured records without removing losing, tied or failed results."""
import json

from .handler import STRATEGIES
from .marginal import digest
from .schemas import PlanningInput


def markdown(records, fixture_dir):
    fixtures = {p.name: PlanningInput.model_validate_json(p.read_text(encoding="utf-8")) for p in sorted(fixture_dir.glob("*.json"))}
    expected = {(name, strategy) for name in fixtures for strategy in STRATEGIES}
    actual = [(r["fixture"], r["strategy"]) for r in records]
    if not expected or set(actual) != expected or len(actual) != len(expected):
        raise ValueError("Evaluation must contain each fixture/strategy exactly once")
    for record in records:
        if record["input_snapshot_sha256"] != digest(fixtures[record["fixture"]].model_dump(mode="json")):
            raise ValueError("Evaluation input hash differs from stored fixture")
    lines = ["# Synthetic planning evaluation", "", "Generated by `pnpm evaluate` from the stored fixtures. All strategies, including ties, losses and failures, remain visible. This is a local software/modelled evaluation; no real dispatch, traffic validation or user outcome is claimed.", "",
             "| Fixture | Closing / loading | Allowance s | Input SHA-256 |", "|---|---|---:|---|"]
    for name, data in fixtures.items():
        lines.append(f"| {name} | {data.service_window_policy} / {data.loading_mode} | {data.solver_time_limit_seconds:g} | `{digest(data.model_dump(mode='json'))}` |")
    lines += ["", "| Scenario | Strategy | Scheduled L | Unmet L | Served points | Critical minimum L | Lowest fulfilment | Travel km | Runtime s | Status | Validator |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---|---|"]
    for record in sorted(records, key=lambda r: (r["fixture"], STRATEGIES.index(r["strategy"]))):
        m = record["metrics"]
        lines.append(f"| {record['fixture'].removesuffix('.json')} | {record['strategy']} | {m['on_time_scheduled_litres']} | {m['unmet_requested_litres']} | {m['served_site_count']} | {m['critical_minimum_litres']} | {m['minimum_fulfilment_ratio']:.1%} | {m['total_travel_distance_metres']/1000:.2f} | {record['runtime_seconds']:.3f} | {record['status']} | {'passed' if record['validation']['valid'] else 'FAILED'} |")
    lines += ["", "## Observed tradeoffs", ""]
    for name in fixtures:
        rows = [r for r in records if r["fixture"] == name]
        jalsetu = next(r for r in rows if r["strategy"] == "jalsetu")
        if not all(r["validation"]["valid"] and r["status"] == "feasible" for r in rows):
            lines.append(f"- {name}: at least one strategy did not produce a checked feasible result; do not infer infeasibility or rank it from zero published volume.")
            continue
        volume = jalsetu["metrics"]["on_time_scheduled_litres"]
        best = max(r["metrics"]["on_time_scheduled_litres"] for r in rows)
        travel = jalsetu["metrics"]["total_travel_distance_metres"]
        least = min(r["metrics"]["total_travel_distance_metres"] for r in rows)
        lines.append(f"- {name}: JalSetu schedules {volume} L; highest recorded volume is {best} L. JalSetu travel is {travel} m; lowest recorded travel is {least} m. These metrics do not establish a universal winner.")
    lines += ["", "## Conditions and limits", "", "All numeric metrics, hashes, validator messages and runtime are retained in [evaluation.json](evaluation.json). Seeds, planning increments, quantities, matrices and windows remain in the referenced fixtures. Runtime and creation time vary by machine/run; this report can be regenerated from its raw records without solving again.", "",
              "No external coordinator participated in this checkpoint. Developer browser exercises are usability smoke checks, not field validation. The separate failure-after-delivery fixture records synthetic loading, a delivery report, failure, conservation and a checked revision; it is not proof of an actual delivery.", "",
              f"Measured {len(records)} calculations. Maximum per-strategy runtime: {max(r['runtime_seconds'] for r in records):.3f} s; sum: {sum(r['runtime_seconds'] for r in records):.3f} s. This sequential fixture run does not establish hosted concurrency or network latency.", ""]
    return "\n".join(lines)


def render(raw_path, fixture_dir, output_path):
    output_path.write_text(markdown(json.loads(raw_path.read_text(encoding="utf-8")), fixture_dir), encoding="utf-8")
